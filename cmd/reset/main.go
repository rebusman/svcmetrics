package main

//go:generate go run . ../..

import (
	"bytes"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"log"
	"os"
	"path/filepath"
	"strings"
)

const (
	marker      = "generate:reset"
	genFileName = "reset.gen.go"
	genHeader   = "// Code generated by cmd/reset; DO NOT EDIT."
)

func main() {
	root := "."
	if len(os.Args) > 1 {
		root = os.Args[1]
	}

	dirs, err := collectDirs(root)
	if err != nil {
		log.Fatal(err)
	}

	loader := newPkgLoader()
	for _, dir := range dirs {
		if err := processDir(dir, loader); err != nil {
			log.Fatalf("%s: %v", dir, err)
		}
	}
}

func collectDirs(root string) ([]string, error) {
	var dirs []string
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			return nil
		}
		name := d.Name()
		if path != root && (strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") ||
			name == "vendor" || name == "testdata") {
			return filepath.SkipDir
		}
		dirs = append(dirs, path)
		return nil
	})
	return dirs, err
}

func processDir(dir string, loader packageLoader) error {
	fset := token.NewFileSet()
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}

	info := newPkgInfo(dir, loader)
	var files []*ast.File

	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") ||
			strings.HasSuffix(name, "_test.go") || name == genFileName {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments)
		if err != nil {
			return err
		}
		if info.name == "" {
			info.name = f.Name.Name
		} else if info.name != f.Name.Name {
			continue
		}
		files = append(files, f)
	}

	for _, f := range files {
		collectDecls(f, info)
	}

	genPath := filepath.Join(dir, genFileName)
	if len(info.targets) == 0 {
		return removeStale(genPath)
	}

	src, err := generate(fset, info)
	if err != nil {
		return err
	}
	return os.WriteFile(genPath, src, 0o644)
}

func removeStale(path string) error {
	data, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if !bytes.HasPrefix(data, []byte(genHeader)) {
		return nil
	}
	return os.Remove(path)
}
